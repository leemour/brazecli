#!/usr/bin/env node
/**
 * Renders `docs/commands.md` from the **live Commander tree**, not from the collection snapshot.
 *
 * The snapshot knows the 95 catalog operations. It does not know that `profile add` exists, that
 * every generated command also takes `--query`, or that a path placeholder became a required
 * option. Only the built program knows what a person can actually type, and `braze commands --json`
 * already walks it — so this renders the same `describeProgram` tree rather than traversing
 * anything of its own. Two walks would drift the first time one learned something the other did
 * not, and "what commands exist" is the fact this repository most refuses to keep in two places.
 *
 * The cost is that this needs `pnpm build` first. CI already builds before its gates, and
 * `docs:check` is placed after that step.
 *
 * `docs/catalog-coverage.md` is deliberately NOT written here. `catalog:generate` owns it and
 * `catalog:check` gates it; a second producer for one file is the failure this script exists to
 * avoid.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")

// `--out` exists so a test can point the gate at a file it controls. Without it the only way to
// prove the gate fails is to corrupt the committed document, which is not a test anyone reruns.
const outFlag = process.argv.indexOf("--out")
if (outFlag !== -1 && process.argv[outFlag + 1] === undefined) {
  console.error("--out needs a path after it")
  process.exit(2)
}
const OUT = outFlag === -1 ? join(root, "docs/commands.md") : process.argv[outFlag + 1]

const { buildProgram } = await import(join(root, "packages/cli/dist/program.js"))
// Resolved from the CLI package: cli-core is its dependency, not the workspace root's.
const registry = createRequire(join(root, "packages/cli/package.json")).resolve("@leemour/cli-core/commands")
const { describeProgram } = await import(pathToFileURL(registry).href)

const check = process.argv.includes("--check")

// An empty config dir, so the tree is the same on every machine. The help footer reads the real
// one otherwise, and the document would then differ between a laptop with profiles and CI.
const program = buildProgram({ env: { BRAZE_CONFIG_DIR: join(root, "node_modules/.cache/brazecli-docs") } })
const commands = describeProgram(program)

const rendered = render(commands, program)

if (check) {
  const current = readOutput(OUT)
  if (current === rendered) {
    console.log(`up to date — ${countLeaves(commands)} runnable commands`)
    process.exit(0)
  }
  console.error(`${OUT} no longer matches the CLI. Run \`pnpm docs:generate\`.`)
  for (const line of firstDifference(current, rendered)) console.error(`  ${line}`)
  process.exit(1)
}

writeFileSync(OUT, rendered)
console.log(`wrote ${OUT} — ${countLeaves(commands)} runnable commands`)

function render(tree, program) {
  const leaves = flatten(tree).filter((command) => command.commands.length === 0)
  const generated = leaves.filter((command) => command.operationId)
  const handwritten = leaves.filter((command) => !command.operationId)

  return [
    "# Commands",
    "",
    "GENERATED by `pnpm docs:generate` from the CLI itself. Do not edit by hand.",
    "",
    "Every command below is walked out of the live program, so this file and",
    "`braze commands --json` can never disagree about what exists.",
    "",
    `${leaves.length} runnable commands: ${handwritten.length} written by hand, ` +
      `${generated.length} generated from [the Braze collection](../spec/braze.postman.json).`,
    "",
    "**A command that talks to Braze names its profile as the first word** — `braze staging",
    "campaigns list`. There is no default profile, deliberately (`NEED-25`). The commands that",
    "never reach Braze — `profile`, `runs`, `commands`, `schema`, `skill`, `update`, `doctor` — take none.",
    "",
    "## Global options",
    "",
    optionTable(program.options.filter((option) => !option.hidden).map(describeOption)),
    "",
    "## Written by hand",
    "",
    ...handwritten.flatMap((command) => section(command)),
    "## Generated from the catalog",
    "",
    "Each of these is one Braze endpoint. `braze schema <operation>` prints its full contract,",
    "including the request body where Braze documents one.",
    "",
    ...generated.flatMap((command) => section(command)),
  ].join("\n")
}

function section(command) {
  const needsProfile = Boolean(command.operationId)
  const usage = ["braze", needsProfile ? "<profile>" : "", ...command.path].filter(Boolean).join(" ")

  const lines = [`### \`${usage}\``, ""]
  if (command.description) lines.push(command.description, "")
  if (command.operationId) lines.push(`Operation \`${command.operationId}\`.`, "")

  const args = command.arguments ?? []
  if (args.length > 0) {
    lines.push(
      "| Argument | Required | |",
      "|---|---|---|",
      ...args.map(
        (argument) => `| \`${argument.name}\` | ${argument.required ? "yes" : "no"} | ${cell(argument.description)} |`,
      ),
      "",
    )
  }

  const options = (command.options ?? []).filter((option) => option.flags !== "-h, --help")
  if (options.length > 0) lines.push(optionTable(options), "")

  return lines
}

function optionTable(options) {
  return [
    "| Option | Required | |",
    "|---|---|---|",
    ...options.map(
      (option) => `| \`${option.flags}\` | ${option.mandatory ? "yes" : "no"} | ${cell(option.description)} |`,
    ),
  ].join("\n")
}

/** A pipe in a description would split the table cell it sits in. */
function cell(text) {
  return (text ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ").trim()
}

function describeOption(option) {
  return { flags: option.flags, description: option.description, mandatory: option.mandatory }
}

function flatten(commands) {
  return commands.flatMap((command) => [command, ...flatten(command.commands)])
}

function countLeaves(commands) {
  return flatten(commands).filter((command) => command.commands.length === 0).length
}

function readOutput(path) {
  try {
    return readFileSync(path, "utf8")
  } catch {
    return undefined
  }
}

/**
 * Names what changed rather than saying "the file differs". A gate that makes you diff by hand to
 * learn what it caught is a gate people learn to regenerate blindly.
 */
function firstDifference(current, next) {
  if (current === undefined) return ["the file does not exist yet"]

  const before = current.split("\n")
  const after = next.split("\n")

  for (let line = 0; line < Math.max(before.length, after.length); line += 1) {
    if (before[line] === after[line]) continue
    return [
      `line ${line + 1} is the first to differ:`,
      `  committed: ${before[line] ?? "(end of file)"}`,
      `  now:       ${after[line] ?? "(end of file)"}`,
    ]
  }
  return ["the files differ in trailing whitespace"]
}
